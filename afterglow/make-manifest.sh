#!/bin/bash
# Builds cache.appcache from the files the page actually needs.
#
# Why a manifest at all: the PS4 browser caches aggressively and there is no
# way to set HTTP headers when the page is served from GitHub Pages. HTML5
# Application Cache is what that browser honours -- it is what the
# established exploit hosts use -- and it caches automatically on the first
# visit, no button to press.
#
# Why the hashes: a manifest only refetches when the MANIFEST ITSELF changes.
# Listing each file with its content hash means any edit changes the manifest,
# so the console picks it up. Without that, an updated page keeps serving the
# old cached one -- the known failure of this mechanism.
#
# Run this after changing any file below, and commit the result.
set -e
cd "$(dirname "$0")"
OUT=cache.appcache
FILES="index.html jb.html style.css launch.js meme.png
       jb.js core.js mem.js int64.js ps4_offsets.js afterglow.js
       patchset-1400.bin patchset-1352.bin hen.bin goldhen.bin"

{
  echo "CACHE MANIFEST"
  echo "# generated by make-manifest.sh -- do not edit by hand"
  echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  for f in $FILES; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
    printf '%s #%s\n' "$f" "$(sha256sum "$f" | cut -c1-32)"
  done
  echo
  echo "NETWORK:"
  echo "*"
} > "$OUT"
echo "$OUT: $(grep -cE '^[^#[:space:]]+ #' "$OUT") entries, $(wc -c < "$OUT") bytes"
